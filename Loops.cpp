int main(){
    int n;
    cin>>n;
    int i = 1;
    while(i<=n){
        int incNum = 1;
        while(incNum<=n-i+1){
            cout<<incNum;
            incNum++;
        }
        int star = 1;
        while(star<=(i-1)*2){
            cout<<"*";
            star++;
        }
        int decNum = n-i+1;
        while(decNum>=1){
            cout<<decNum;
            decNum--;
        }
        cout<<endl;
        i++;
    }
}